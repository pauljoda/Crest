using System.Globalization;
using System.Text;

namespace CrestCore.Generator;

/// Emits the TypeScript contract models and their codec for the desktop
/// interface, which renders the read model in a page and talks to the core
/// over the same wire Swift does. Records become read-only interfaces; the
/// members of a root also carry their name as `$kind` and get a factory that
/// adds it. Enums become numeric enums, fixed sets frozen member objects whose
/// wire tag is their index in `all`, and each root a union type with a reader
/// and a writer. A record a message the interface sends holds travels as its
/// seed, its fields alone.
internal static class TypeScriptEmitter {
    #region Static Variables

    private const string Header = """
        // <auto-generated/>
        // Generated by CrestCore/tools/CrestCore.Generator from the C# contract records. Do not edit.
        /* eslint-disable */

        import { WireReader, WireWriter } from "./wire";

        """;

    private static readonly HashSet<string> Reserved = new(StringComparer.Ordinal) {
        "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else",
        "enum", "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof",
        "new", "null", "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void",
        "while", "with", "let", "static", "yield", "await", "implements", "interface", "package", "private",
        "protected", "public"
    };

    #endregion

    #region Actions - Emitting

    public static string Emit(ContractSchema schema) {
        ArgumentNullException.ThrowIfNull(schema);
        var code = new StringBuilder(Header);
        code.Append('\n').Append("/** SHA-256 of the canonical contract schema, which the core refuses any other than. */\n");
        code.Append($"export const fingerprint = Uint8Array.of({Bytes(schema.Fingerprint)});\n");
        code.Append("/** SHA-256 of the engine contract alone, which an engine binding registers with. */\n");
        code.Append($"export const engineFingerprint = Uint8Array.of({Bytes(schema.EngineFingerprint)});\n");

        var members = new Dictionary<Type, (ContractRoot Root, ContractMember Member)>();
        foreach (var root in ContractRoot.All)
            foreach (var member in schema.Members(root)) members[member.Record.Type] = (root, member);

        if (schema.Enums.Count > 0) code.Append("\n// Enums\n");
        foreach (var item in schema.Enums) {
            code.Append('\n').Append($"export enum {item.Name} {{\n");
            foreach (var member in item.Members) code.Append($"    {member.Key} = {member.Value},\n");
            code.Append("}\n");
        }

        if (schema.Sets.Count > 0) code.Append("\n// Fixed sets\n");
        foreach (var set in Ordered(schema.Sets)) EmitSet(code, set, members);

        code.Append("\n// Records\n");
        foreach (var record in schema.Records) EmitRecord(code, schema, record, members);

        code.Append("\n// Roots\n");
        foreach (var root in ContractRoot.All) EmitRoot(code, schema, root);
        foreach (var family in schema.Families.Concat(schema.Bases).DistinctBy(family => family.Base))
            EmitFamily(code, schema, family);

        code.Append("\n// Codec\n");
        foreach (var root in ContractRoot.All) EmitRootCodec(code, schema, root);
        foreach (var narrowed in schema.Bases) EmitBaseCodec(code, schema, narrowed);
        foreach (var record in schema.Records) EmitRecordCodec(code, schema, record, members);
        foreach (var item in schema.Enums) EmitEnumCodec(code, item);
        foreach (var set in schema.Sets.Where(set => !set.IsOpen)) EmitSetCodec(code, set);
        return code.ToString();
    }

    #endregion

    #region Actions - Declarations

    /// A fixed set's members are frozen objects of the set's interface, and
    /// the set's value holds them, `all`, its constants and `named`. A member
    /// whose data names another set's member comes after that set.
    private static void EmitSet(StringBuilder code, ContractSet set, Dictionary<Type, (ContractRoot Root, ContractMember Member)> members) {
        code.Append('\n');
        foreach (var kinds in set.Properties.Select(property => property.Type).OfType<KindsField>().DistinctBy(kinds => kinds.Type)) {
            code.Append($"export enum {set.Name}{kinds.Type.Name} {{\n");
            foreach (string kind in Enum.GetNames(kinds.Type)) code.Append($"    {kind} = \"{kind}\",\n");
            code.Append("}\n\n");
        }
        code.Append(set.IsOpen
            ? $"/** A member of the core's `{set.Name}`, which also makes members at runtime. */\n"
            : $"/** A member of the core's `{set.Name}`. Its wire tag is its index in `all`. */\n");
        code.Append($"export interface {set.Name} {{\n");
        if (!set.IsOpen) code.Append("    readonly tag: number;\n");
        foreach (var property in set.Properties)
            code.Append($"    readonly {Member(property.Name)}: {TypeName(property.Type, set)};\n");
        code.Append("}\n\n");
        foreach (var member in set.Members) {
            var values = new List<string>();
            if (!set.IsOpen) values.Add($"tag: {member.Tag}");
            values.AddRange(set.Properties.Select((property, index) =>
                $"{Member(property.Name)}: {Literal(property.Type, member.Values[index], set, members)}"));
            code.Append($"const {set.Name}_{member.Name}: {set.Name} = Object.freeze({{ {string.Join(", ", values)} }});\n");
        }
        bool named = set.Properties.Any(property => property.Name == "Name");
        code.Append($"export const {set.Name} = Object.freeze({{\n");
        foreach (var constant in set.Constants)
            code.Append($"    {Member(constant.Name)}: {Literal(constant.Type, constant.Value, set, members)},\n");
        foreach (var member in set.Members) code.Append($"    {Member(member.Name)}: {set.Name}_{member.Name},\n");
        code.Append($"    all: [{string.Join(", ", set.Members.Select(member => $"{set.Name}_{member.Name}"))}] as readonly {set.Name}[],\n");
        if (named)
            code.Append($"    named(name: string | null | undefined): {set.Name} | undefined {{\n"
                + $"        return {set.Name}.all.find(member => member.name === name);\n    }},\n");
        code.Append("});\n");
    }

    private static void EmitRecord(StringBuilder code, ContractSchema schema, ContractRecord record,
        Dictionary<Type, (ContractRoot Root, ContractMember Member)> members) {
        bool isMember = members.TryGetValue(record.Type, out var owner);
        bool sends = isMember && owner.Root.PlatformSends;
        code.Append('\n').Append($"export interface {record.Name} {{\n");
        if (isMember) code.Append($"    readonly $kind: \"{record.Name}\";\n");
        foreach (var field in record.Wire)
            code.Append($"    readonly {Member(field.Name)}: {TypeName(field.Type, null, seeds: sends, schema)};\n");
        code.Append("}\n");
        if (isMember) {
            string fields = record.Wire.Count == 0 ? "" : $"fields: Omit<{record.Name}, \"$kind\">";
            string spread = record.Wire.Count == 0 ? "" : ", ...fields";
            code.Append($"export function {record.Name}({fields}): {record.Name} {{\n");
            code.Append($"    return {{ $kind: \"{record.Name}\"{spread} }};\n}}\n");
        }
        if (schema.HasSeed(record.Type)) {
            code.Append($"/** What the interface sends of a `{record.Name}`: its fields, without the values the core resolves. */\n");
            code.Append($"export interface {record.Name}Seed {{\n");
            foreach (var field in record.Fields)
                code.Append($"    readonly {Member(field.Name)}: {TypeName(field.Type, null, seeds: true, schema)};\n");
            code.Append("}\n");
        }
        if (record.Statics.Count > 0) {
            code.Append($"export const {record.Name}Statics = Object.freeze({{\n");
            foreach (var constant in record.Statics)
                code.Append($"    {Member(constant.Name)}: {Literal(constant.Type, constant.Value, null, members)},\n");
            code.Append("});\n");
        }
        if (record.Texts.Count > 0) {
            code.Append($"/** The English texts of a `{record.Name}`; `%lld` stands for the field each names. */\n");
            code.Append($"export const {record.Name}Texts = Object.freeze({{\n");
            foreach (var text in record.Texts)
                code.Append($"    {Member(text.Name)}: Object.freeze({{ text: {StringLiteral(text.Text)}"
                    + (text.Argument is { } argument ? $", argument: {StringLiteral(Member(argument))}" : "") + " }),\n");
            code.Append("});\n");
        }
    }

    /// A root is the union of its members. A root with answers also maps each
    /// member to the type it answers with.
    private static void EmitRoot(StringBuilder code, ContractSchema schema, ContractRoot root) {
        var members = schema.Members(root);
        code.Append('\n').Append($"export type {root.Name} =\n");
        code.Append(members.Count == 0 ? "    never;\n" : string.Join("\n", members.Select(member => $"    | {member.Name}")) + ";\n");
        if (!root.PlatformSends) EmitRootTexts(code, root, members);
        if (!root.HasAnswer) return;
        code.Append($"/** What each `{root.Name}` answers with. */\n");
        code.Append($"export interface {root.Name}Answers {{\n");
        foreach (var member in members)
            code.Append($"    {member.Name}: {TypeName(member.Answer!, null)};\n");
        code.Append("}\n");
        code.Append($"export type AnswerOf{root.Name}<Q extends {root.Name}> = {root.Name}Answers[Q[\"$kind\"]];\n");
    }

    /// Each text some members of a root the interface receives carry is read
    /// through the root, as Swift's enum reads it: the member's English with
    /// its argument filled in, or null for a member without it.
    private static void EmitRootTexts(StringBuilder code, ContractRoot root, IReadOnlyList<ContractMember> members) {
        foreach (string name in members.SelectMany(member => member.Record.Texts).Select(text => text.Name).Distinct()
                     .Order(StringComparer.Ordinal)) {
            code.Append($"/** The `{Member(name)}` a `{root.Name}` carries, or null for one that carries none. */\n");
            code.Append($"export function {Member(name)}Of{root.Name}(value: {root.Name}): string | null {{\n");
            code.Append("    switch (value.$kind) {\n");
            foreach (var member in members) {
                if (member.Record.Texts.FirstOrDefault(text => text.Name == name) is not { } text) continue;
                string literal = StringLiteral(text.Text);
                string filled = text.Argument is { } argument
                    ? $"{literal}.replace(\"%lld\", value.{Member(argument)}.toLocaleString())"
                    : literal;
                code.Append($"        case \"{member.Name}\": return {filled};\n");
            }
            code.Append("        default: return null;\n    }\n}\n");
        }
    }

    private static void EmitFamily(StringBuilder code, ContractSchema schema, RootField family) {
        var members = schema.Members(ContractRoot.All.First(root => root == family.Root))
            .Where(member => family.Base!.IsAssignableFrom(member.Record.Type)).ToList();
        code.Append('\n').Append($"/** The members of `{family.Root}` that derive from the core's `{family.Base!.Name}`. */\n");
        code.Append($"export type {family.Base!.Name} =\n");
        code.Append(members.Count == 0 ? "    never;\n" : string.Join("\n", members.Select(member => $"    | {member.Name}")) + ";\n");
    }

    #endregion

    #region Actions - Codec

    private static void EmitRootCodec(StringBuilder code, ContractSchema schema, ContractRoot root) {
        var members = schema.Members(root);
        code.Append('\n').Append($"export function read{root.Name}(reader: WireReader): {root.Name} {{\n");
        code.Append("    const tag = reader.readTag();\n    switch (tag) {\n");
        foreach (var member in members) code.Append($"        case {member.Tag}: return read{member.Name}(reader);\n");
        code.Append($"        default: throw new Error(`Unknown {root.Name} tag ${{tag}}.`);\n    }}\n}}\n");

        code.Append('\n').Append($"export function write{root.Name}(writer: WireWriter, value: {root.Name}): void {{\n");
        code.Append("    switch (value.$kind) {\n");
        foreach (var member in members)
            code.Append($"        case \"{member.Name}\": writer.writeTag({member.Tag}); write{member.Name}(writer, value); break;\n");
        code.Append($"        default: throw new Error(`Not a contract {root.Name}: ${{(value as {{ $kind: string }}).$kind}}.`);\n    }}\n}}\n");

        if (!root.HasAnswer) return;
        code.Append('\n').Append($"/** Reads what `question` answers with. */\n");
        code.Append($"export function read{root.Name}Answer<Q extends {root.Name}>(question: Q, reader: WireReader): AnswerOf{root.Name}<Q> {{\n");
        code.Append("    switch (question.$kind) {\n");
        foreach (var member in members)
            code.Append($"        case \"{member.Name}\": return ({Read(member.Answer!)}) as unknown as AnswerOf{root.Name}<Q>;\n");
        code.Append($"        default: throw new Error(`Not a contract {root.Name}: ${{(question as {{ $kind: string }}).$kind}}.`);\n    }}\n}}\n");
        code.Append('\n').Append($"/** Writes what `question` answers with. */\n");
        code.Append($"export function write{root.Name}Answer<Q extends {root.Name}>(question: Q, writer: WireWriter, value: AnswerOf{root.Name}<Q>): void {{\n");
        code.Append("    switch (question.$kind) {\n");
        foreach (var member in members) {
            code.Append($"        case \"{member.Name}\": {{\n");
            code.Append($"            const answer = value as {root.Name}Answers[\"{member.Name}\"];\n");
            code.Append(Write(member.Answer!, "answer", "            ", "answer", null, seeds: false));
            code.Append("            break;\n        }\n");
        }
        code.Append($"        default: throw new Error(`Not a contract {root.Name}: ${{(question as {{ $kind: string }}).$kind}}.`);\n    }}\n}}\n");
    }

    private static void EmitBaseCodec(StringBuilder code, ContractSchema schema, RootField narrowed) {
        string name = narrowed.Base!.Name;
        code.Append('\n').Append($"export function read{name}(reader: WireReader): {name} {{\n");
        code.Append("    const tag = reader.readTag();\n    switch (tag) {\n");
        foreach (var member in schema.Members(narrowed)) code.Append($"        case {member.Tag}: return read{member.Name}(reader);\n");
        code.Append($"        default: throw new Error(`{narrowed.Root} tag ${{tag}} is not a {name}.`);\n    }}\n}}\n");
        code.Append($"export function write{name}(writer: WireWriter, value: {name}): void {{\n    write{narrowed.Root}(writer, value);\n}}\n");
    }

    /// A record reads everything the core writes of it, its fields and then
    /// its resolved values. It writes its fields, holding seeds where a record
    /// it holds has one, which is all the core reads from the interface.
    private static void EmitRecordCodec(StringBuilder code, ContractSchema schema, ContractRecord record,
        Dictionary<Type, (ContractRoot Root, ContractMember Member)> members) {
        bool isMember = members.ContainsKey(record.Type);
        code.Append('\n').Append($"export function read{record.Name}(reader: WireReader): {record.Name} {{\n");
        foreach (var field in record.Wire) code.Append($"    const {Local(field.Name)} = {Read(field.Type)};\n");
        var assigned = new List<string>();
        if (isMember) assigned.Add($"$kind: \"{record.Name}\"");
        assigned.AddRange(record.Wire.Select(field => Member(field.Name) == Local(field.Name)
            ? Member(field.Name) : $"{Member(field.Name)}: {Local(field.Name)}"));
        code.Append($"    return {{ {string.Join(", ", assigned)} }};\n}}\n");

        string type = schema.HasSeed(record.Type) ? $"{record.Name}Seed" : record.Name;
        string parameter = record.Fields.Count == 0 ? "_value" : "value";
        code.Append($"export function write{record.Name}(writer: WireWriter, {parameter}: {type}): void {{\n");
        foreach (var field in record.Fields)
            code.Append(Write(field.Type, $"value.{Member(field.Name)}", "    ", Local(field.Name), schema, seeds: true));
        code.Append("}\n");
        if (schema.HasSeed(record.Type))
            code.Append($"export const write{record.Name}Seed = write{record.Name};\n");
    }

    private static void EmitEnumCodec(StringBuilder code, ContractEnum item) {
        string read = item.IsFlags
            ? $"reader.readFlags({item.Members.Aggregate(0, (mask, member) => mask | member.Value)})"
            : $"reader.readEnum({item.Members.Count})";
        code.Append('\n').Append($"export function read{item.Name}(reader: WireReader): {item.Name} {{\n    return {read} as {item.Name};\n}}\n");
        code.Append($"export function write{item.Name}(writer: WireWriter, value: {item.Name}): void {{\n    writer.writeEnum(value);\n}}\n");
    }

    private static void EmitSetCodec(StringBuilder code, ContractSet set) {
        code.Append('\n').Append($"export function read{set.Name}(reader: WireReader): {set.Name} {{\n");
        code.Append($"    return {set.Name}.all[reader.readEnum({set.Name}.all.length)];\n}}\n");
        code.Append($"export function write{set.Name}(writer: WireWriter, value: {set.Name}): void {{\n    writer.writeEnum(value.tag);\n}}\n");
    }

    private static string Read(FieldType type) => type switch {
        PrimitiveField primitive => $"reader.read{Method(primitive.Kind)}()",
        EnumField item => $"read{item.Type.Name}(reader)",
        SetField set => $"read{set.Type.Name}(reader)",
        RecordField record => $"read{record.Type.Name}(reader)",
        RootField { Base: { } narrowed } => $"read{narrowed.Name}(reader)",
        RootField root => $"read{root.Root}(reader)",
        ListField list => $"reader.readList(() => {Read(list.Element)})",
        OptionalField optional => $"(reader.readPresence() ? {Read(optional.Value)} : null)",
        _ => throw new ContractSchemaException($"Cannot read {type} in TypeScript.")
    };

    private static string Write(FieldType type, string value, string indent, string scope, ContractSchema? schema, bool seeds) => type switch {
        PrimitiveField primitive => $"{indent}writer.write{Method(primitive.Kind)}({value});\n",
        EnumField item => $"{indent}write{item.Type.Name}(writer, {value});\n",
        SetField set => $"{indent}write{set.Type.Name}(writer, {value});\n",
        RecordField record => $"{indent}write{record.Type.Name}(writer, {value});\n",
        RootField { Base: { } narrowed } => $"{indent}write{narrowed.Name}(writer, {value});\n",
        RootField root => $"{indent}write{root.Root}(writer, {value});\n",
        ListField list => $"{indent}writer.writeCount({value}.length);\n"
            + $"{indent}for (const {scope}Item of {value}) {{\n"
            + Write(list.Element, $"{scope}Item", indent + "    ", $"{scope}Item", schema, seeds)
            + $"{indent}}}\n",
        OptionalField optional => $"{indent}if ({value} !== null && {value} !== undefined) {{\n"
            + $"{indent}    writer.writePresence(true);\n"
            + Write(optional.Value, value, indent + "    ", $"{scope}Value", schema, seeds)
            + $"{indent}}} else {{\n{indent}    writer.writePresence(false);\n{indent}}}\n",
        _ => throw new ContractSchemaException($"Cannot write {type} in TypeScript.")
    };

    private static string Method(Primitive kind) => kind switch {
        Primitive.Int => "Int32",
        Primitive.Long => "Int64",
        Primitive.ULong => "UInt64",
        _ => kind.ToString()
    };

    #endregion

    #region Actions - Types

    /// A field's TypeScript type. With `seeds`, a record that has a seed is
    /// spelled as its seed, as a message the interface sends holds it.
    private static string TypeName(FieldType type, ContractSet? set, bool seeds = false, ContractSchema? schema = null) => type switch {
        PrimitiveField { Kind: Primitive.Bool } => "boolean",
        PrimitiveField { Kind: Primitive.Int or Primitive.Double or Primitive.Duration } => "number",
        PrimitiveField { Kind: Primitive.Long or Primitive.ULong } => "bigint",
        PrimitiveField { Kind: Primitive.String or Primitive.Guid } => "string",
        PrimitiveField { Kind: Primitive.Date } => "Date",
        PrimitiveField { Kind: Primitive.Bytes } => "Uint8Array",
        EnumField item => item.Type.Name,
        SetField reference => reference.Type.Name,
        RecordField record => seeds && schema!.HasSeed(record.Type) ? $"{record.Type.Name}Seed" : record.Type.Name,
        RootField { Base: { } narrowed } => narrowed.Name,
        RootField root => root.Root.Name,
        ListField list => $"readonly {Grouped(TypeName(list.Element, set, seeds, schema))}[]",
        OptionalField optional => $"{TypeName(optional.Value, set, seeds, schema)} | null",
        LocalizedField => "string",
        KindsField kinds => $"{set!.Name}{kinds.Type.Name}",
        _ => throw new ContractSchemaException($"Cannot name {type} in TypeScript.")
    };

    private static string Grouped(string type) => type.Contains(' ', StringComparison.Ordinal) ? $"({type})" : type;

    #endregion

    #region Actions - Literals

    /// A fixed set member's data value as a TypeScript literal.
    private static string Literal(FieldType type, object? value, ContractSet? set,
        Dictionary<Type, (ContractRoot Root, ContractMember Member)> members) => (type, value) switch {
            (OptionalField, null) => "null",
            (OptionalField optional, _) => Literal(optional.Value, value, set, members),
            (PrimitiveField, bool flag) => flag ? "true" : "false",
            (PrimitiveField { Kind: Primitive.Long or Primitive.ULong }, int or long or ulong) =>
                Convert.ToString(value, CultureInfo.InvariantCulture) + "n",
            (PrimitiveField, int or long or ulong) => Convert.ToString(value, CultureInfo.InvariantCulture)!,
            (PrimitiveField, double number) => NumberLiteral(number),
            (PrimitiveField, TimeSpan duration) => NumberLiteral(duration.TotalSeconds),
            (PrimitiveField, string text) => StringLiteral(text),
            (SetField, SetMemberReference reference) => $"{reference.Set.Name}_{reference.Member}",
            (KindsField kinds, Enum kind) => $"{set!.Name}{kinds.Type.Name}.{kind}",
            (EnumField item, Enum member) => EnumLiteral(item, member),
            (ListField list, IReadOnlyList<object?> items) =>
                $"Object.freeze([{string.Join(", ", items.Select(item => Literal(list.Element, item, set, members)))}])",
            (RecordField, RecordValue record) => RecordLiteral(record, set, members),
            (LocalizedField, LocalizedText text) => StringLiteral(text.Text),
            _ => throw new ContractSchemaException($"Cannot spell {value} as a TypeScript {type}.")
        };

    private static string RecordLiteral(RecordValue record, ContractSet? set,
        Dictionary<Type, (ContractRoot Root, ContractMember Member)> members) {
        var values = new List<string>();
        if (members.ContainsKey(record.Record.Type)) values.Add($"$kind: \"{record.Record.Name}\"");
        values.AddRange(record.Record.Wire.Select((field, index) =>
            $"{Member(field.Name)}: {Literal(field.Type, record.Values[index], set, members)}"));
        return $"Object.freeze({{ {string.Join(", ", values)} }})";
    }

    private static string EnumLiteral(EnumField item, Enum value) {
        if (!item.Type.IsDefined(typeof(FlagsAttribute), false)) return $"{item.Type.Name}.{value}";
        long bits = Convert.ToInt64(value, CultureInfo.InvariantCulture);
        if (bits == 0) return "0";
        var named = Enum.GetValues(item.Type).Cast<Enum>()
            .Select(member => (Name: member.ToString(), Bits: Convert.ToInt64(member, CultureInfo.InvariantCulture)))
            .Where(member => member.Bits != 0 && (bits & member.Bits) == member.Bits).OrderBy(member => member.Bits).ToList();
        if (named.Aggregate(0L, (covered, member) => covered | member.Bits) != bits)
            throw new ContractSchemaException($"Cannot spell {item.Type.Name} value {bits} from its named members.");
        return string.Join(" | ", named.Select(member => $"{item.Type.Name}.{member.Name}"));
    }

    private static string NumberLiteral(double number) => number switch {
        double.NaN => "Number.NaN",
        double.PositiveInfinity => "Number.POSITIVE_INFINITY",
        double.NegativeInfinity => "Number.NEGATIVE_INFINITY",
        _ => number.ToString("R", CultureInfo.InvariantCulture)
    };

    private static string StringLiteral(string text) {
        var literal = new StringBuilder("\"");
        foreach (var rune in text.EnumerateRunes())
            literal.Append(rune.Value switch {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < 0x20 or 0x7f or 0x2028 or 0x2029 => $"\\u{{{rune.Value:x}}}",
                _ => rune.ToString()
            });
        return literal.Append('"').ToString();
    }

    private static string Bytes(byte[] values) => string.Join(", ", values.Select(value => $"0x{value:x2}"));

    #endregion

    #region Actions - Names

    /// A property name: lowerCamel (`ProfileId` becomes `profileId`).
    private static string Member(string name) {
        var words = Naming.Words(name);
        return words[0].ToLowerInvariant() + string.Concat(words.Skip(1));
    }

    /// A local variable, escaped when it is a reserved word.
    private static string Local(string name) {
        string member = Member(name);
        return Reserved.Contains(member) ? $"{member}_" : member;
    }

    /// The fixed sets in an order where each comes after the sets its
    /// members' data names, since a member is a constant the next ones read.
    private static List<ContractSet> Ordered(IReadOnlyList<ContractSet> sets) {
        var byType = sets.ToDictionary(set => set.Type);
        var ordered = new List<ContractSet>();
        var state = new Dictionary<Type, bool>();
        void Visit(ContractSet set) {
            if (state.TryGetValue(set.Type, out bool done)) {
                if (!done) throw new ContractSchemaException($"Fixed set {set.Name} refers to itself through another set.");
                return;
            }
            state[set.Type] = false;
            foreach (var referenced in set.Members.SelectMany(member => member.Values).SelectMany(References).Distinct())
                if (referenced != set.Type && byType.TryGetValue(referenced, out var other)) Visit(other);
            state[set.Type] = true;
            ordered.Add(set);
        }
        foreach (var set in sets) Visit(set);
        return ordered;
    }

    private static IEnumerable<Type> References(object? value) => value switch {
        SetMemberReference reference => [reference.Set],
        RecordValue record => record.Values.SelectMany(References),
        IReadOnlyList<object?> items => items.SelectMany(References),
        _ => []
    };

